"""Validate every results/runs/*/run.json and rebuild INDEX.md and index.json.

    python3 results/tools/index.py                 # validate and rebuild
    python3 results/tools/index.py --check         # fail if anything is invalid or the index is stale
    python3 results/tools/index.py find --demo report-reconciliation --kind live-comparison --model opus

Standard library only, so it runs without any demo's virtual environment.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

RESULTS = Path(__file__).resolve().parents[1]
REPO = RESULTS.parent
RUNS = RESULTS / "runs"

KINDS = {"live-comparison", "baseline", "rehearsal", "controls", "regression", "preflight", "historical-comparison"}
STATUSES = {"completed", "partial", "blocked", "failed", "aborted"}
PROVENANCE = {"live-model", "deterministic", "historical"}
REVIEW = {"pending", "done", "not-applicable"}
REQUIRED = {"id": str, "date": str, "demo": str, "demo_path": str, "kind": str, "status": str, "provenance": str,
            "models": list, "headline": str, "repo_commit": str, "files": dict, "human_review": str}
ID_PATTERN = re.compile(r"(\d{4}-\d{2}-\d{2})_([a-z0-9-]+)_([a-z0-9-]+)(?:_([a-z0-9.-]+))?")


def validate(path):
    errors = []
    try:
        run = json.loads(path.read_text())
    except ValueError as error:
        return None, [f"{path}: invalid JSON ({error})"]
    for field, kind in REQUIRED.items():
        if not isinstance(run.get(field), kind):
            errors.append(f"{path}: '{field}' must be a {kind.__name__}")
    if errors:
        return run, errors
    match = ID_PATTERN.fullmatch(run["id"])
    if run["id"] != path.parent.name:
        errors.append(f"{path}: id '{run['id']}' must equal its directory name")
    if not match:
        errors.append(f"{path}: id must look like YYYY-MM-DD_<demo>_<kind>[_<variant>]")
    elif (match[1], match[2], match[3]) != (run["date"], run["demo"], run["kind"]):
        errors.append(f"{path}: id must start with its date, demo and kind")
    for field, allowed in (("kind", KINDS), ("status", STATUSES), ("provenance", PROVENANCE), ("human_review", REVIEW)):
        if run[field] not in allowed:
            errors.append(f"{path}: {field} '{run[field]}' is not one of {sorted(allowed)}")
    if not (REPO / run["demo_path"]).is_dir():
        errors.append(f"{path}: demo_path '{run['demo_path']}' does not exist")
    for role, target in run["files"].items():
        # Paths starting with ./ are inside the run folder; others are relative to the repository root.
        resolved = path.parent / target if target.startswith("./") else REPO / target
        if not resolved.exists():
            errors.append(f"{path}: files.{role} -> '{target}' does not exist")
    return run, errors


def load():
    runs, errors = [], []
    for path in sorted(RUNS.glob("*/run.json")):
        run, problems = validate(path)
        errors += problems
        if run and not problems:
            runs.append(run)
    return sorted(runs, key=lambda run: (run["date"], run["id"]), reverse=True), errors


def link(run, target):
    return f"runs/{run['id']}/{target[2:]}" if target.startswith("./") else f"../{target}"


def render(runs):
    lines = ["# Results index", "",
             "Generated by `python3 results/tools/index.py` from `runs/*/run.json`. Do not edit by hand.", "",
             "| Date | Demo | Kind | Models | Status | Headline | Record |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for run in runs:
        models = ", ".join(f"`{model}`" for model in run["models"]) or "none"
        record = f"[{run['id']}](runs/{run['id']}/run.json)"
        lines.append(f"| {run['date']} | {run['demo']} | {run['kind']} | {models} | {run['status']} | "
                     f"{run['headline'].replace('|', '/')} | {record} |")
    lines += ["", f"{len(runs)} runs.", ""]
    return "\n".join(lines)


def outputs(runs):
    index = [{key: run.get(key) for key in ("id", "date", "demo", "kind", "status", "provenance", "models",
              "conditions", "headline", "metrics", "cost_usd", "human_review", "tags")} |
             {"path": f"runs/{run['id']}"} for run in runs]
    return {RESULTS / "INDEX.md": render(runs), RESULTS / "index.json": json.dumps(index, indent=2) + "\n"}


def find(runs, args):
    for run in runs:
        if args.demo and args.demo not in run["demo"]:
            continue
        if args.kind and args.kind != run["kind"]:
            continue
        if args.model and not any(args.model in model for model in run["models"]):
            continue
        if args.tag and args.tag not in run.get("tags", []):
            continue
        print(f"{run['id']}\n  {run['headline']}\n  results/runs/{run['id']}/")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    sub = parser.add_subparsers(dest="command")
    query = sub.add_parser("find")
    for name in ("demo", "kind", "model", "tag"):
        query.add_argument(f"--{name}")
    args = parser.parse_args()
    runs, errors = load()
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    if args.command == "find":
        find(runs, args)
        return 0
    stale = [path for path, text in outputs(runs).items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"{path.relative_to(REPO)} is stale; run python3 results/tools/index.py", file=sys.stderr)
        return int(bool(stale))
    for path, text in outputs(runs).items():
        path.write_text(text)
    print(f"Indexed {len(runs)} runs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
